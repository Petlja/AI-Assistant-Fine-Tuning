"""Batch commands: submit and fetch for OpenAI Batch API."""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import click
from openai import OpenAI

from ai_assistant_fine_tuning.batch_util import (
    load_manifest,
    save_manifest,
    update_manifest_batch_state,
    utc_now_iso,
    write_jsonl,
)
from ai_assistant_fine_tuning.data_gen import (
    DEFAULT_THRESHOLD,
    route_evaluation,
    transform_evaluate_batch,
    transform_questions_batch,
    write_readable_evaluation_raw,
    write_readable_questions_raw,
)

logger = logging.getLogger(__name__)

TERMINAL_BATCH_STATES = {"completed", "failed", "expired", "cancelled"}


def _safe_text_from_file_content(file_content: Any) -> str:
    text_attr = getattr(file_content, "text", None)
    if callable(text_attr):
        return text_attr()
    if isinstance(text_attr, str):
        return text_attr

    content_attr = getattr(file_content, "content", None)
    if callable(content_attr):
        data = content_attr()
        if isinstance(data, bytes):
            return data.decode("utf-8")
        return str(data)

    if isinstance(file_content, bytes):
        return file_content.decode("utf-8")

    return str(file_content)


def _parse_chat_completion_content(line: dict[str, Any]) -> str:
    response = line.get("response") or {}
    body = response.get("body") or {}
    choices = body.get("choices") or []
    if not choices:
        raise ValueError("Missing choices in response body")

    message = choices[0].get("message") or {}
    content = message.get("content")
    if isinstance(content, list):
        text_parts = [item.get("text", "") for item in content if isinstance(item, dict)]
        content = "".join(text_parts)

    if not isinstance(content, str) or not content.strip():
        raise ValueError("Missing assistant message content")

    return content


@click.command("batch-submit")
@click.option(
    "--manifest",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    required=True,
    help="Path to manifest JSON generated by gen-batch.",
)
@click.option(
    "--batch-input",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    default=None,
    help="Optional override path to batch input JSONL.",
)
def batch_submit(manifest: Path, batch_input: Path | None) -> None:
    """Submit a prepared batch input file to OpenAI Batch API."""
    manifest_obj = load_manifest(manifest)
    batch_input_path = batch_input or Path(manifest_obj["batch_input_file"])
    if not batch_input_path.exists():
        raise click.ClickException(f"Batch input file does not exist: {batch_input_path}")

    client = OpenAI()

    click.echo(f"Uploading batch input: {batch_input_path}")
    with open(batch_input_path, "rb") as f:
        uploaded_file = client.files.create(file=f, purpose="batch")

    click.echo("Creating batch job...")
    batch_obj = client.batches.create(
        input_file_id=uploaded_file.id,
        endpoint="/v1/chat/completions",
        completion_window="24h",
        metadata={"task": manifest_obj.get("task", "unknown")},
    )

    manifest_obj.setdefault("batch", {})
    update_manifest_batch_state(manifest_obj, batch_obj)
    manifest_obj["batch"]["submitted_at"] = utc_now_iso()
    manifest_obj["batch"]["input_file_id"] = uploaded_file.id

    save_manifest(manifest_obj, manifest)

    click.echo(f"Batch submitted: {batch_obj.id}")
    click.echo(f"Status: {batch_obj.status}")


@click.command("fetch-batch")
@click.option(
    "--manifest",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    required=True,
    help="Path to manifest JSON.",
)
@click.option(
    "--output",
    "output_path",
    type=click.Path(dir_okay=False, path_type=Path),
    default=None,
    help="Optional override for final output path.",
)
@click.option(
    "--readable-output",
    type=click.Path(dir_okay=False, path_type=Path),
    default=None,
    help="Optional override for readable text output path.",
)
@click.option(
    "--threshold",
    type=click.IntRange(1, 10),
    default=None,
    help="Score threshold for evaluate task (overrides manifest value).",
)
@click.option(
    "--append/--overwrite",
    default=False,
    show_default=True,
    help="Append to existing output files instead of overwriting.",
)
def fetch_batch(
    manifest: Path,
    output_path: Path | None,
    readable_output: Path | None,
    threshold: int | None,
    append: bool,
) -> None:
    """Check batch status and fetch results if complete.

    If the batch is still running, prints current status and exits.
    If the batch is in a terminal state, downloads outputs and transforms
    them into the appropriate format (questions JSONL or SFT/DPO JSONL).
    """
    manifest_obj = load_manifest(manifest)
    task = manifest_obj.get("task")
    if task not in {"questions", "evaluate"}:
        raise click.ClickException("Manifest task must be either 'questions' or 'evaluate'.")

    batch_id = manifest_obj.get("batch", {}).get("id")
    if not batch_id:
        raise click.ClickException("Manifest does not contain a batch id. Run batch-submit first.")

    client = OpenAI()
    batch_obj = client.batches.retrieve(batch_id)
    update_manifest_batch_state(manifest_obj, batch_obj)

    # If not terminal, report status and exit.
    if batch_obj.status not in TERMINAL_BATCH_STATES:
        save_manifest(manifest_obj, manifest)
        counts = manifest_obj.get("batch", {}).get("request_counts") or {}
        click.echo(f"Batch: {batch_id}")
        click.echo(f"Status: {batch_obj.status}")
        if counts:
            click.echo(
                "Requests: "
                f"total={counts.get('total', 0)} "
                f"completed={counts.get('completed', 0)} "
                f"failed={counts.get('failed', 0)}"
            )
        click.echo("Batch is not complete yet. Re-run this command later.")
        return

    # Terminal state — attempt to fetch results.
    output_file_id = getattr(batch_obj, "output_file_id", None)
    if not output_file_id:
        save_manifest(manifest_obj, manifest)
        raise click.ClickException("Batch has no output file.")

    output_text = _safe_text_from_file_content(client.files.content(output_file_id))
    output_lines: list[dict[str, Any]] = []
    for raw_line in output_text.splitlines():
        raw_line = raw_line.strip()
        if raw_line:
            output_lines.append(json.loads(raw_line))

    requests = manifest_obj.get("requests", [])
    requests_by_id = {req["custom_id"]: req for req in requests}

    if task == "questions":
        _process_questions_batch(
            output_lines, requests_by_id, manifest_obj, output_path, readable_output, append,
        )
    elif task == "evaluate":
        effective_threshold = threshold or manifest_obj.get("threshold", DEFAULT_THRESHOLD)
        _process_evaluate_batch(
            output_lines, requests_by_id, manifest_obj, effective_threshold,
            output_path, readable_output, append,
        )

    # Process error file if present.
    error_file_id = getattr(batch_obj, "error_file_id", None)
    if error_file_id:
        error_text = _safe_text_from_file_content(client.files.content(error_file_id))
        for raw_line in error_text.splitlines():
            raw_line = raw_line.strip()
            if not raw_line:
                continue
            error_line = json.loads(raw_line)
            custom_id = error_line.get("custom_id")
            req = requests_by_id.get(custom_id)
            if req is not None and req.get("status") != "succeeded":
                req["status"] = "failed_api"

    # Mark unresolved requests.
    for req in requests:
        if req.get("status") not in {"succeeded", "failed_api", "failed_parse", "skipped_too_short"}:
            req["status"] = "missing_output"

    # Update manifest summary.
    manifest_obj["fetched_at"] = utc_now_iso()
    manifest_obj["summary"] = {
        "succeeded_requests": sum(1 for req in requests if req.get("status") == "succeeded"),
        "failed_api_requests": sum(1 for req in requests if req.get("status") == "failed_api"),
        "failed_parse_requests": sum(1 for req in requests if req.get("status") == "failed_parse"),
        "missing_output_requests": sum(1 for req in requests if req.get("status") == "missing_output"),
    }
    save_manifest(manifest_obj, manifest)

    click.echo(f"Fetched {len(output_lines)} batch output line(s)")
    click.echo(f"Manifest updated -> {manifest}")


def _process_questions_batch(
    output_lines: list[dict[str, Any]],
    requests_by_id: dict[str, dict],
    manifest_obj: dict[str, Any],
    output_path: Path | None,
    readable_output: Path | None,
    append: bool,
) -> None:
    """Process batch output for task=questions."""
    final_output_path = output_path or Path(manifest_obj["final_output_file"])
    final_readable_path = readable_output or Path(manifest_obj["final_readable_file"])

    final_records: list[dict[str, Any]] = []
    readable_items: list[dict[str, Any]] = []

    for line in output_lines:
        custom_id = line.get("custom_id")
        if not custom_id:
            continue

        manifest_req = requests_by_id.get(custom_id)
        if manifest_req is None:
            continue

        error = line.get("error")
        response = line.get("response") or {}
        status_code = response.get("status_code")

        if error is not None or status_code != 200:
            manifest_req["status"] = "failed_api"
            continue

        try:
            content = _parse_chat_completion_content(line)
            parsed_json = json.loads(content)
            system_message, questions = transform_questions_batch(parsed_json)

            source = manifest_req.get("source_rel_path", custom_id)
            record = {
                "source": source,
                "system_message": system_message,
                "questions": questions,
            }
            final_records.append(record)
            readable_items.append({
                "source": source,
                "system_message": system_message,
                "questions": questions,
            })

            manifest_req["status"] = "succeeded"
            manifest_req["generated_count"] = len(questions)
        except Exception:
            manifest_req["status"] = "failed_parse"

    if final_records:
        write_jsonl(final_records, final_output_path, append=append)
        write_readable_questions_raw(readable_items, final_readable_path, append=append)

    total_questions = sum(len(r["questions"]) for r in final_records)
    click.echo(f"Generated {total_questions} questions from {len(final_records)} source(s) -> {final_output_path}")


def _process_evaluate_batch(
    output_lines: list[dict[str, Any]],
    requests_by_id: dict[str, dict],
    manifest_obj: dict[str, Any],
    threshold: int,
    output_path: Path | None,
    readable_output: Path | None,
    append: bool,
) -> None:
    """Process batch output for task=evaluate."""
    final_sft_path = output_path or Path(manifest_obj["final_sft_file"])
    final_dpo_path = Path(manifest_obj["final_dpo_file"])
    final_readable_path = readable_output or Path(manifest_obj["final_readable_file"])

    sft_records: list[dict[str, Any]] = []
    dpo_records: list[dict[str, Any]] = []
    readable_items: list[dict[str, Any]] = []

    for line in output_lines:
        custom_id = line.get("custom_id")
        if not custom_id:
            continue

        manifest_req = requests_by_id.get(custom_id)
        if manifest_req is None:
            continue

        error = line.get("error")
        response = line.get("response") or {}
        status_code = response.get("status_code")

        if error is not None or status_code != 200:
            manifest_req["status"] = "failed_api"
            continue

        try:
            content = _parse_chat_completion_content(line)
            parsed_json = json.loads(content)
            eval_result = transform_evaluate_batch(parsed_json)

            source = manifest_req.get("source", custom_id)
            system_message = manifest_req.get("system_message", "")
            question = manifest_req.get("question", "")
            answer = manifest_req.get("answer", "")

            sft_rec, dpo_rec = route_evaluation(
                system_message, question, answer, eval_result, threshold,
            )

            routed_to = "SFT" if sft_rec else "DPO"
            if sft_rec:
                sft_records.append(sft_rec)
            if dpo_rec:
                dpo_records.append(dpo_rec)

            readable_items.append({
                "source": source,
                "question": question,
                "answer": answer,
                "score": eval_result.score,
                "improved_answer": eval_result.improved_answer,
                "routed_to": routed_to,
            })

            manifest_req["status"] = "succeeded"
            manifest_req["score"] = eval_result.score
            manifest_req["routed_to"] = routed_to
        except Exception:
            manifest_req["status"] = "failed_parse"

    if sft_records:
        write_jsonl(sft_records, final_sft_path, append=append)
    if dpo_records:
        write_jsonl(dpo_records, final_dpo_path, append=append)
    if readable_items:
        write_readable_evaluation_raw(readable_items, final_readable_path, append=append)

    click.echo(f"SFT: {len(sft_records)} records -> {final_sft_path}")
    click.echo(f"DPO: {len(dpo_records)} records -> {final_dpo_path}")
